/** The geometry name comes from properties.ts (Turkish); map the common VSEPR names for the English UI. */
export function geometryLabel(name: string, lang: Language): string {
  if (lang === 'tr') return name
  for (const [re, label] of GEOMETRY_EN) if (re.test(name)) return label
  return name
}

const SUP_DIGITS: Record<string, string> = { '0': '⁰', '1': '¹', '2': '²', '3': '³' }
/** sp3 -> sp³ */
export const hybridLabel = (h: string): string => h.replace(/^(sp)([0-3])$/, (_m, a: string, d: string) => a + (SUP_DIGITS[d] ?? d))

/** One shared locale-aware number formatter (Intl.NumberFormat) for inspector and status bar. */
const nfCache = new Map<string, Intl.NumberFormat>()
export function fmtNum(lang: Language, n: number, digits: number): string {
  const key = `${lang}:${digits}`
  let f = nfCache.get(key)
  if (!f) {
    f = new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-US', { minimumFractionDigits: digits, maximumFractionDigits: digits })
    nfCache.set(key, f)
  }
  return f.format(n).replace('-', '−')
}

export type NumFmt = (n: number, digits: number) => string
export function useFmt(): NumFmt {
  const lang = useStudio((s) => s.language)
  return useCallback((n: number, digits: number) => fmtNum(lang, n, digits), [lang])
}
