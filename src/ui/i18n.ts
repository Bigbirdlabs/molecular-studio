const DICT: Record<Language, Record<TrKey, string>> = { tr: tr as unknown as Record<TrKey, string>, en }

/** Both dictionaries (exposed for the key-parity test). */
export const dictionaries = DICT

const PLURAL_RE = /\{(\w+):([^|}]*)\|([^}]*)\}/g
const PARAM_RE = /\{(\w+)\}/g

export function translate(lang: Language, key: TrKey, params?: Params): string {
  const raw = DICT[lang][key] ?? DICT.tr[key] ?? key
  if (!params) return raw
  return raw
    .replace(PLURAL_RE, (_m, name: string, one: string, many: string) => (Number(params[name]) === 1 ? one : many))
    .replace(PARAM_RE, (m, name: string) => (name in params ? String(params[name]) : m))
}

/** Non-reactive translation (event handlers, toasts). Components should use useT(). */
export const t = (key: TrKey, params?: Params): string => translate(useStudio.getState().language, key, params)

export type TFn = (key: TrKey, params?: Params) => string

/** Reactive translation hook: components re-render when the language changes. */
export function useT(): TFn {
  const lang = useStudio((s) => s.language)
  return useCallback((key: TrKey, params?: Params) => translate(lang, key, params), [lang])
}

export const hasKey = (key: string): key is TrKey => key in tr

/** Functional-group names arrive as stable ids from properties.ts; fall back to the supplied Turkish name. */
export function groupLabel(id: string, fallback: string, lang: Language): string {
  const key = `fg.${id}`
  return hasKey(key) ? translate(lang, key) : fallback
}

